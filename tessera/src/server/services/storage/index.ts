import { createReadStream } from 'node:fs';
import { mkdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { Readable } from 'node:stream';
import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { env } from '../../env';

export interface ByteRange {
  start: number;
  /** Inclusive; omitted means "to the end". */
  end?: number;
}

export interface StoredObject {
  body: ReadableStream<Uint8Array>;
  /** Bytes in `body` (the requested range, or the whole object). */
  size: number;
  /** Size of the whole object. */
  total: number;
  /** The range actually served, when one was asked for. */
  range?: { start: number; end: number };
}

/** Where uploaded images and audio live. Swap drivers with STORAGE_DRIVER. */
export interface StorageDriver {
  put(key: string, data: Uint8Array, contentType: string): Promise<void>;
  /** Reads an object, optionally only a byte range (audio seeking needs this). */
  get(key: string, range?: ByteRange): Promise<StoredObject | null>;
  delete(key: string): Promise<void>;
}

/** Keys are generated by the server, but never trust a path all the same. */
function assertSafeKey(key: string): void {
  if (!/^[a-zA-Z0-9][a-zA-Z0-9/_.-]*$/.test(key) || key.includes('..')) {
    throw new Error(`unsafe storage key: ${key}`);
  }
}

class LocalStorage implements StorageDriver {
  constructor(private readonly root: string) {}

  private file(key: string): string {
    assertSafeKey(key);
    return path.join(this.root, key);
  }

  async put(key: string, data: Uint8Array): Promise<void> {
    const file = this.file(key);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, data);
  }

  async get(key: string, range?: ByteRange): Promise<StoredObject | null> {
    const file = this.file(key);
    try {
      const info = await stat(file);
      const total = info.size;
      if (range && total > 0) {
        const start = Math.min(range.start, total - 1);
        const end = Math.min(range.end ?? total - 1, total - 1);
        const stream = createReadStream(file, { start, end });
        return { body: Readable.toWeb(stream) as ReadableStream<Uint8Array>, size: end - start + 1, total, range: { start, end } };
      }
      return { body: Readable.toWeb(createReadStream(file)) as ReadableStream<Uint8Array>, size: total, total };
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code === 'ENOENT') return null;
      throw err;
    }
  }

  async delete(key: string): Promise<void> {
    await rm(this.file(key), { force: true });
  }
}

class S3Storage implements StorageDriver {
  private readonly client = new S3Client({
    region: env.S3_REGION,
    endpoint: env.S3_ENDPOINT,
    forcePathStyle: env.S3_FORCE_PATH_STYLE,
    credentials: { accessKeyId: env.S3_ACCESS_KEY_ID!, secretAccessKey: env.S3_SECRET_ACCESS_KEY! },
  });
  private readonly bucket = env.S3_BUCKET!;

  async put(key: string, data: Uint8Array, contentType: string): Promise<void> {
    assertSafeKey(key);
    await this.client.send(
      new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: data, ContentType: contentType }),
    );
  }

  async get(key: string, range?: ByteRange): Promise<StoredObject | null> {
    assertSafeKey(key);
    try {
      const out = await this.client.send(
        new GetObjectCommand({
          Bucket: this.bucket,
          Key: key,
          Range: range ? `bytes=${range.start}-${range.end ?? ''}` : undefined,
        }),
      );
      if (!out.Body) return null;
      const size = out.ContentLength ?? 0;
      // "bytes 0-99/1234": the part after the slash is the full object size.
      const served = /^bytes (\d+)-(\d+)\/(\d+)$/.exec(out.ContentRange ?? '');
      return {
        body: out.Body.transformToWebStream() as ReadableStream<Uint8Array>,
        size,
        total: served ? Number(served[3]) : size,
        range: served ? { start: Number(served[1]), end: Number(served[2]) } : undefined,
      };
    } catch (err) {
      const name = (err as { name?: string }).name;
      if (name === 'NoSuchKey' || name === 'NotFound') return null;
      throw err;
    }
  }

  async delete(key: string): Promise<void> {
    assertSafeKey(key);
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

/**
 * Netlify Blobs: object storage built into Netlify, configured automatically
 * inside Netlify functions. Ranges are served by slicing, since uploads are a
 * few megabytes at most.
 */
class NetlifyBlobsStorage implements StorageDriver {
  private store: Promise<import('@netlify/blobs').Store> | null = null;
  private open() {
    this.store ??= import('@netlify/blobs').then(({ getStore }) => getStore({ name: 'tessera-media', consistency: 'strong' }));
    return this.store;
  }

  async put(key: string, data: Uint8Array, contentType: string): Promise<void> {
    assertSafeKey(key);
    const copy = new Uint8Array(data);
    await (await this.open()).set(key, copy.buffer, { metadata: { contentType } });
  }

  async get(key: string, range?: ByteRange): Promise<StoredObject | null> {
    assertSafeKey(key);
    const data = (await (await this.open()).get(key, { type: 'arrayBuffer' })) as ArrayBuffer | null;
    if (!data) return null;
    const bytes = new Uint8Array(data);
    const total = bytes.length;
    let slice = bytes;
    let served: { start: number; end: number } | undefined;
    if (range && total > 0) {
      const start = Math.min(range.start, total - 1);
      const end = Math.min(range.end ?? total - 1, total - 1);
      slice = bytes.subarray(start, end + 1);
      served = { start, end };
    }
    return { body: new Blob([slice]).stream(), size: slice.length, total, range: served };
  }

  async delete(key: string): Promise<void> {
    assertSafeKey(key);
    await (await this.open()).delete(key);
  }
}

/** Files in the database's stored_files table: no extra service or disk needed. */
export class DatabaseStorage implements StorageDriver {
  async put(key: string, data: Uint8Array, contentType: string): Promise<void> {
    assertSafeKey(key);
    const { db } = await import('../../db/client');
    const { storedFiles } = await import('../../db/schema');
    await db
      .insert(storedFiles)
      .values({ key, contentType, data: Buffer.from(data) })
      .onConflictDoUpdate({ target: storedFiles.key, set: { contentType, data: Buffer.from(data) } });
  }

  async get(key: string, range?: ByteRange): Promise<StoredObject | null> {
    assertSafeKey(key);
    const { db } = await import('../../db/client');
    const { storedFiles } = await import('../../db/schema');
    const { eq } = await import('drizzle-orm');
    const [row] = await db.select({ data: storedFiles.data }).from(storedFiles).where(eq(storedFiles.key, key)).limit(1);
    if (!row) return null;
    const bytes = new Uint8Array(row.data);
    const total = bytes.length;
    let slice = bytes;
    let served: { start: number; end: number } | undefined;
    if (range && total > 0) {
      const start = Math.min(range.start, total - 1);
      const end = Math.min(range.end ?? total - 1, total - 1);
      slice = bytes.subarray(start, end + 1);
      served = { start, end };
    }
    return { body: new Blob([slice]).stream(), size: slice.length, total, range: served };
  }

  async delete(key: string): Promise<void> {
    assertSafeKey(key);
    const { db } = await import('../../db/client');
    const { storedFiles } = await import('../../db/schema');
    const { eq } = await import('drizzle-orm');
    await db.delete(storedFiles).where(eq(storedFiles.key, key));
  }
}

export const storage: StorageDriver =
  env.STORAGE_DRIVER === 's3'
    ? new S3Storage()
    : env.STORAGE_DRIVER === 'netlify'
      ? new NetlifyBlobsStorage()
      : env.STORAGE_DRIVER === 'database'
        ? new DatabaseStorage()
        : new LocalStorage(path.resolve(env.STORAGE_LOCAL_DIR));
